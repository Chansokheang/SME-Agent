"""Turns the approved Prisma design into PostgreSQL tables in the owner's own database.

The design file targets SQLite (that's what the build stage develops against), so it is
re-pointed at PostgreSQL in a temp copy and Prisma generates the exact CREATE statements.
"""

import os
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

import psycopg

from .db_connect import normalize

PRISMA = "prisma@6"


class SchemaSqlError(RuntimeError):
    pass


class TablesExist(RuntimeError):
    def __init__(self, tables: list[str]):
        super().__init__(", ".join(tables))
        self.tables = tables


def design_tables(prisma_text: str) -> list[str]:
    """Table names the design creates (model name, or its @@map name)."""
    names = []
    for match in re.finditer(r"^model\s+(\w+)\s*\{(.*?)^\}", prisma_text, re.MULTILINE | re.DOTALL):
        mapped = re.search(r'@@map\("([^"]+)"\)', match.group(2))
        names.append(mapped.group(1) if mapped else match.group(1))
    return names


def postgres_sql(prisma_text: str) -> str:
    """CREATE TABLE / INDEX / FOREIGN KEY statements for PostgreSQL, generated by Prisma."""
    schema = re.sub(r'provider\s*=\s*"sqlite"', 'provider = "postgresql"', prisma_text)
    schema = re.sub(r'url\s*=\s*"file:[^"]*"', 'url      = env("DATABASE_URL")', schema)
    npx = shutil.which("npx")
    if not npx:
        raise SchemaSqlError("Node.js (npx) is needed to generate the SQL.")
    # On Windows a lingering npx child can hold the folder open; don't fail the request over cleanup.
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as folder:
        path = Path(folder) / "schema.prisma"
        path.write_text(schema, encoding="utf-8")
        # A placeholder URL: migrate diff only reads the file, it never connects.
        env = {**os.environ, "DATABASE_URL": "postgresql://placeholder:placeholder@localhost:5432/placeholder"}
        result = subprocess.run(
            [npx, "--yes", PRISMA, "migrate", "diff", "--from-empty", "--to-schema-datamodel", str(path), "--script"],
            capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=240, env=env,
        )
    if result.returncode != 0 or "CREATE TABLE" not in result.stdout:
        raise SchemaSqlError((result.stderr or result.stdout).strip()[-1500:] or "Prisma could not generate the SQL.")
    return result.stdout.strip()


def existing_tables(url: str) -> set[str]:
    with psycopg.connect(normalize(url), connect_timeout=8) as conn:
        rows = conn.execute(
            "select table_name from information_schema.tables where table_schema = 'public' and table_type = 'BASE TABLE'"
        ).fetchall()
    return {r[0] for r in rows}


def create_tables(url: str, sql: str, tables: list[str]) -> None:
    """Runs the script in one transaction: every table is created, or nothing changes."""
    with psycopg.connect(normalize(url), connect_timeout=8) as conn:
        rows = conn.execute(
            "select table_name from information_schema.tables where table_schema = 'public'"
        ).fetchall()
        clash = sorted(set(tables) & {r[0] for r in rows})
        if clash:
            raise TablesExist(clash)
        conn.execute(sql)  # no parameters, so several statements run in one go
        conn.commit()
